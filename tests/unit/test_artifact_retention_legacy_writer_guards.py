def test_weight_writer_preserves_manifest_bytes_after_component_loop(
    tmp_path, monkeypatch
):
    """Actual writer I/O with explicit serializer/replay doubles, not science."""
    module = _module("data_quality.training_weight_artifacts")
    manifest_json = '{"manifest":"generated-only-I/O-control"}'
    components = {"a.json": b"first component", "z.json": b"last component"}
    monkeypatch.setattr(
        module,
        "_manifest",
        lambda _: (SimpleNamespace(to_json=lambda: manifest_json), components),
    )
    replayed = []
    monkeypatch.setattr(
        module,
        "replay_training_weight_candidate_shard",
        lambda shard, *, approval: replayed.append((shard, approval)),
    )
    root = tmp_path / "ordinary"
    result = module.write_training_weight_candidate_shard(None, root)
    assert replayed == [(None, None)]
    assert result.read_bytes() == manifest_json.encode("ascii")
    for name, raw in components.items():
        assert (root / name).read_bytes() == raw
