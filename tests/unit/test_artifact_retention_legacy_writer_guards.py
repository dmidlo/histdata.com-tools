def _module(name):
    return importlib.import_module("histdatacom." + name)


def _mark(path, kind="file"):
    path.mkdir(parents=True)
    marker = path / MANAGED_ARTIFACT_MARKER
    if kind == "file":
        marker.write_bytes(b"invalid but present marker")
    elif kind == "directory":
        marker.mkdir()
    else:
        marker.symlink_to("absent-marker-target")
    (path / "protected.bin").write_bytes(b"immutable generated bytes")
    return path


def _snapshot(root):
    return {
        path.relative_to(root).as_posix(): (
            ("link", str(path.readlink()))
            if path.is_symlink()
            else (
                ("directory", "")
                if path.is_dir()
                else ("file", path.read_bytes())
            )
        )
        for path in sorted(root.rglob("*"))
    }


@pytest.mark.parametrize("module_name,function_name", _DIRECTORY_WRITERS)
@pytest.mark.parametrize("marker_kind", ("file", "directory", "symlink"))
def test_directory_writer_refuses_before_mkdir_or_model_access(
    tmp_path, module_name, function_name, marker_kind
):
    writer = getattr(_module(module_name), function_name)
    protected = _mark(tmp_path / "managed", marker_kind)
    before = _snapshot(tmp_path)
    with pytest.raises(ManagedArtifactBoundaryError):
        writer(None, protected / "must-not-create" / "nested")
    assert _snapshot(tmp_path) == before


